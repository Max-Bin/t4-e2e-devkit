"""Strict-fp32 scoping for the GPU proposal rollout and scoring.

The rollout in :mod:`t4_e2e_devkit.evaluation.gpu.simulate` fits two batched
least-squares problems per call -- ``a_t @ a`` plus ``torch.linalg.solve`` in
the velocity and curvature profile fits, and the lateral-LQR products.  Under
``torch.set_float32_matmul_precision("high")`` those fp32 matmuls are eligible
for TF32 tensor cores, which carry a 10-bit mantissa instead of 24.

Whether that eligibility is *taken* depends on how many rows the caller passes,
which is why this went unnoticed:

* :func:`t4_e2e_devkit.evaluation.navsim_score.score_proposals` flattens to one
  :class:`Trajectory` per call and round-trips through ``.cpu().numpy()``, so
  the rollout sees a single row and cuBLAS never selects a TF32 kernel.  Both
  public scoring entry points are unaffected at any window count.
* A caller that scores a whole training batch in one call -- an online label
  oracle at ``windows x proposals`` rows, or
  ``script/score_prediction_manifest.py --compile-rollout`` -- reaches the
  size where cuBLAS does select one.

Measured at 256 rows (4 windows x 64 proposals) on
``jpntaxi-val-prdjtval-filt-s50``, TF32 against strict fp32: the simulated
states move by up to 8.658e-03 on 90 948 of 115 456 elements.  Downstream that
surfaces as ``ego_progress`` moving by 8.2e-04 on 115 of 256 proposals and
``driving_direction_compliance`` *flipping a discrete class* by 0.5 on one
proposal sitting on the route-angle threshold.  Scoring is bit-exact when fed
identical simulated states, so the rollout is the only source.

That matters because a label is a *target*: it has to mean the same number in
every run and agree with the reference the evaluation path reports against.
Pinning fp32 costs -0.03 ms of a 47.9 ms warm scoring pass -- nothing, because
these matmuls are small least-squares fits rather than the large GEMMs TF32
exists to accelerate.

Two reasons this wraps the vendored function instead of setting the precision at
each call site:

* ``simulate.py`` is generated by ``tools/vendor.py`` and every numeric
  expression in it is byte-identical to its numpy reference, so a hand edit
  there would be reverted by the next sync.
* the CUDA-graph cache in ``_rollout_maybe_compiled`` is keyed by config,
  shapes, dtype and device index -- *not* by matmul precision.  A graph
  captured while TF32 was active keeps replaying TF32 kernels for every later
  caller of that shape, including one that has since asked for ``"highest"``.
  Guarding the entry point puts the capture itself under strict fp32.

Autocast
--------
TF32 is not the only process precision setting that reaches these matmuls.
``torch.autocast`` is a second one, it is what a mixed-precision *training* loop
leaves enabled around everything it calls, and it is far more destructive here
than TF32 was:

* ``a_t @ a`` and ``torch.einsum`` in the two profile fits are on autocast's
  lower-precision list, so under ``bf16`` they hand a bf16 matrix to
  ``torch.linalg.solve``, which does not implement it:
  ``NotImplementedError: "lu_factor_magma_batched" not implemented for
  'BFloat16'``.  An fp16 autocast would not even fail loudly -- ``solve``
  accepts it and returns a least-squares fit with a 10-bit mantissa.
* the kernels downstream of the rollout carry the same exposure, which is why a
  training caller wants this guard around a whole scoring pass and not just the
  simulation.  ``collisions.py`` projects box corners with ``einsum`` and
  ``comfort.py`` applies its Savitzky-Golay filter as ``signal @ matrix.T``
  before rounding to 8 decimals; driven under bf16, 3 of 4096 synthetic
  near-touching quads flip their intersection verdict and the comfort filter
  moves by 1.56e-02 (``tests/test_gpu_precision.py``).  Note what this is *not*:
  every metric ends in a threshold comparison, so the scores come back fp32
  either way, and no real-window label has been measured to move.  The scope is
  there to keep a discrete threshold crossing from depending on the caller's
  precision, not to repair an observed drift.

So the guard disables autocast as well as pinning TF32 off.  A label is a
target: it must depend on its inputs and on nothing else about the process that
computed it.  The graph-cache argument above applies unchanged -- the cache is
not keyed by autocast state either, so the capture has to happen inside the
guard.
"""

from __future__ import annotations

import contextlib
from typing import Iterator

import torch

from t4_e2e_devkit.evaluation.gpu.simulate import (
    TorchSimulatorConfig,
    simulate_proposals_torch,
)

__all__ = ["simulate_proposals_fp32", "strict_fp32_matmul"]

# Autocast is per device type, and asking for one the build does not support
# raises, so the guard suppresses the types that exist rather than a fixed list.
_AUTOCAST_DEVICE_TYPES = ("cuda", "cpu", "xpu")


@contextlib.contextmanager
def strict_fp32_matmul() -> Iterator[None]:
    """Force strict fp32 matmuls, whatever precision the process has set.

    Pins ``float32_matmul_precision`` to ``"highest"``, turns cuDNN's TF32 off,
    and disables autocast, then restores all three.  Safe to nest: every setting
    is saved and put back, so an inner scope is a no-op.
    """

    precision = torch.get_float32_matmul_precision()
    cudnn_tf32 = torch.backends.cudnn.allow_tf32
    torch.set_float32_matmul_precision("highest")
    torch.backends.cudnn.allow_tf32 = False
    try:
        with contextlib.ExitStack() as stack:
            for device_type in _AUTOCAST_DEVICE_TYPES:
                if torch.amp.is_autocast_available(device_type):
                    stack.enter_context(torch.autocast(device_type, enabled=False))
            yield
    finally:
        torch.set_float32_matmul_precision(precision)
        torch.backends.cudnn.allow_tf32 = cudnn_tf32


def simulate_proposals_fp32(
    proposal_states: torch.Tensor,  # [N, T+1, 11]
    initial_states: torch.Tensor,  # [N, 11]
    config: TorchSimulatorConfig,
    compile_rollout: bool = False,
) -> torch.Tensor:  # [N, T+1, 11]
    """:func:`simulate_proposals_torch` with precision-independent results.

    Use this rather than the vendored function directly: it is the same
    simulation, and it makes the output depend only on the inputs instead of
    also on the process's matmul precision, on whether autocast happens to be
    enabled around the call, and on who captured the rollout graph first.

    A caller that goes on to *score* the simulated states wants
    :func:`strict_fp32_matmul` around the whole pass instead -- the metric
    kernels carry their own autocast exposure, which this per-call guard cannot
    cover.
    """

    with strict_fp32_matmul():
        return simulate_proposals_torch(
            proposal_states, initial_states, config, compile_rollout
        )
